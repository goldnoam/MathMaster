// Merge topic quizzes from STATIC_DATA_DB so every lesson's questions are also searchable in the Question Bank
const buildMergedBank = (): BankQuestion[] => {
  const result: BankQuestion[] = [...HANDCRAFTED_BANK];
  const existingKeys = new Set(result.map((q) => `${q.topicId}::${q.question.trim()}`));

  CURRICULUM.forEach((grade) => {
    const gradeData = STATIC_DATA_DB[grade.id];
    if (!gradeData) return;

    grade.topics.forEach((topic) => {
      const topicContent = gradeData.topics[topic.id];
      if (!topicContent || !Array.isArray(topicContent.quiz)) return;

      topicContent.quiz.forEach((q, idx) => {
        const key = `${topic.id}::${q.question.trim()}`;
        if (existingKeys.has(key)) return;
        existingKeys.add(key);

        const inferredDiff: Difficulty =
          idx === 0 ? 'easy' : idx === topicContent.quiz.length - 1 ? 'hard' : 'medium';

        result.push({
          ...q,
          id: `static-${grade.id}-${topic.id}-${idx}`,
          gradeId: grade.id,
          gradeName: grade.name,
          topicId: topic.id,
          topicName: topic.name,
          category: topic.category || 'אלגברה',
          difficulty: q.difficulty || inferredDiff,
          fullSolution:
            q.fullSolution && q.fullSolution.length > 0
              ? q.fullSolution
              : [
                  ...(q.hint ? [`רמז מנחה: ${q.hint}`] : []),
                  q.explanation,
                  `תשובה סופית נכונה: ${q.options[q.correctAnswerIndex]}`,
                ],
        });
      });
    });
  });

  return result;
};

export const QUESTION_BANK: BankQuestion[] = buildMergedBank();
